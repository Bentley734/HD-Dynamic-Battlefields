"""Assemble a review catalog from source artwork; never enable Gen 2 implicitly.

Reuses Gen 1 paths and perspective inheritance, keeps independently composed
night geometry, and rejects missing/changed source files before emitting data.
Mound bindings and geometry remain calibration candidates until gameplay review.
"""
import copy
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASPECTS = ['4x3', '16x9', '16x10', '3x2', '21x9', '32x9', '9x16', '9x19_5', '9x20']


def lua(value):
    if isinstance(value, dict):
        return '{' + ','.join('[' + json.dumps(k) + ']=' + lua(v)
                              for k, v in sorted(value.items())) + '}'
    if isinstance(value, list):
        return '{' + ','.join(map(lua, value)) + '}'
    if value is None:
        return 'nil'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    return json.dumps(value, ensure_ascii=False, allow_nan=False)


def main():
    reuse = json.loads((ROOT / 'metadata/gen2-reuse-plan.json').read_text())
    bindings = json.loads((ROOT / 'metadata/gen2-mound-bindings.json').read_text())['families']
    metadata = copy.deepcopy(reuse['metadata'])
    entries = [copy.deepcopy(e) for f in reuse['families'] for e in f['compositions']]
    ids = {e['id'] for e in entries}
    records = {}
    for path in sorted((ROOT / 'art/gen2').glob('*/*/*.authoring.json')):
        record = json.loads(path.read_text())
        image = ROOT / record['background']
        if hashlib.sha256(image.read_bytes()).hexdigest() != record['sha256']:
            raise ValueError('Source changed since authoring review: ' + str(image))
        records[record['composition_id']] = record

    def geometry(record):
        aspect = record['aspect_ratio']
        template = ('meadow-perspective-32x9' if aspect == '32:9' else
                    'meadow-perspective-9x16' if aspect.startswith('9:') else
                    'meadow-perspective-16x9')
        result = {k: copy.deepcopy(record[k]) for k in
                  ('schema_version', 'composition_id', 'reference_size', 'aspect_ratio',
                   'horizon_y', 'depth', 'safe_area', 'player', 'opponent')}
        result['inherits'] = template
        return result

    for identifier, record in sorted(records.items()):
        if identifier.endswith('-night'):
            continue
        if identifier in ids:
            raise ValueError('Duplicate reused/new composition: ' + identifier)
        family = Path(record['background']).parent.name
        binding = bindings[family]
        aspect = record['aspect_ratio']
        metadata[identifier] = geometry(record)
        entry = {'id': identifier, 'environment': family, 'variation': 1,
                 'aspect_ratio': aspect, 'quality': 'HD', 'metadata': identifier,
                 'background': record['background'],
                 'mounds': {side: binding['day'] for side in ('player', 'opponent')}}
        night = records.get(identifier + '-night')
        if night:
            metadata[night['composition_id']] = geometry(night)
            entry.update(backgrounds={'day': record['background'], 'night': night['background']},
                         night_metadata=night['composition_id'],
                         night_mounds={side: binding['night'] for side in ('player', 'opponent')})
        entries.append(entry)
        ids.add(identifier)

    families = sorted({e['environment'] for e in entries})
    for family in families:
        actual = {e['aspect_ratio'].replace(':', 'x').replace('.', '_')
                  for e in entries if e['environment'] == family}
        if actual != set(ASPECTS):
            raise ValueError('Incomplete aspect coverage: ' + family)
    for entry in entries:
        paths = [entry['background']]
        for field in ('backgrounds', 'mounds', 'night_mounds'):
            paths.extend(entry.get(field, {}).values())
        for relative in paths:
            if not (ROOT / relative).is_file():
                raise ValueError('Missing catalog texture: ' + relative)
    result = {'stage': 'Gen 2 integration candidate; gameplay calibration pending',
              'metadata': metadata, 'compositions': sorted(entries, key=lambda e: e['id'])}
    (ROOT / 'metadata/gen2.lua').write_text(
        '-- Generated by tools/build_gen2_catalog.py; review inputs, not this file.\nreturn ' +
        lua(result) + '\n', encoding='utf-8')
    print(json.dumps({'compositions': len(entries), 'families': len(families),
                      'night_geometry': sum('night_metadata' in e for e in entries),
                      'gameplay_validated': False}))


if __name__ == '__main__':
    main()
