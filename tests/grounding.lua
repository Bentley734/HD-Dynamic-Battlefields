local G=assert(loadfile(root..'/lib/grounding.lua'))()
local P=assert(loadfile(root..'/lib/perspective.lua'))()
local S=assert(loadfile(root..'/lib/scene.lua'))()
local catalog=assert(loadfile(root..'/metadata/prototype.lua'))()
local profile=assert(loadfile(root..'/metadata/native_gen1.lua'))()
local scene=S.new({},P,function()end)
scene.metadata=assert(P.resolve(catalog.metadata,'grassland-01-16x9'))
local viewport={width=1920,height=1080}
local base=assert(scene:layout(viewport))
local adjusted=assert(scene:layout(viewport,{global={player={mound_x=.01,mound_y=-.02,mound_scale=1.5}}}))
assert(G.apply(adjusted,base,profile))
assert(math.abs(adjusted.player.mound.x-(400+36*7+19.2))<1e-8)
assert(math.abs(adjusted.player.mound.y-(36+96*7-21.6))<1e-8)
assert(adjusted.player.mound.scale==1.5 and adjusted.player.mound.bounds[1]==profile.player.width*7)
assert(math.abs(base.player.mound.x-.28*1920)<1e-8,'Authored metadata was mutated')
local explicit=assert(scene:layout(viewport))
assert(G.apply(explicit,base,profile,{x=10,y=20,width=320,height=288}))
assert(explicit.opponent.mound.x==266 and explicit.opponent.mound.y==132)
assert(not G.apply(explicit,base,profile,{x=0/0,y=0,width=1,height=1}))
local aspect=assert(scene:layout(viewport,{global={player={mound_x=.01}},aspects={['16:9']={player={mound_x=.02}}}}))
assert(G.apply(aspect,base,profile));assert(math.abs(aspect.player.mound.x-(400+36*7+38.4))<1e-8)
print('PASS native scenery anchoring, integer fit, exact consumer frame, saved/global/aspect offsets and scaling, immutable metadata and invalid-frame rejection')
